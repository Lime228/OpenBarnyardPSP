#!/usr/bin/env python3

import argparse
import pathlib


GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
CELL_WIDTH = 8
CELL_HEIGHT = 8
ATLAS_COLUMNS = 8
ATLAS_WIDTH = 64
ATLAS_HEIGHT = 32
CHARACTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ-."

